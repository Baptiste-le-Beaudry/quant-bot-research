"""
pipeline.py — the mandatory redundancy check (SPEC.md section 5): drop any
feature with |correlation| > 0.9 to an already-kept feature, keeping
whichever of the two has higher mutual information with the label. This is
not optional and not a one-time thing — rerun it whenever the candidate
feature list in quant_bot.features.build changes, and keep the report.
"""

import pandas as pd
from sklearn.feature_selection import mutual_info_classif, mutual_info_regression


def prune_redundant(features: pd.DataFrame, label: pd.Series, corr_threshold: float = 0.9,
                     random_state: int = 42, max_rows: int = 150_000,
                     regression: bool = False) -> tuple[list, dict]:
    """max_rows: mutual_info_classif's k-NN estimator is the expensive part
    here (O(n log n) per feature) — on this project's ~1.26M-row combined
    TRAIN set it was taking several minutes, long enough to be fragile in
    this environment. A random subsample of max_rows is standard practice
    for MI estimation and doesn't meaningfully change which features get
    kept (this is a screen, not the final model fit — the model itself
    still trains on the full data).

    regression=True: use mutual_info_regression for a continuous label
    (quant_bot.features.build.build_regression_label, option 2 in
    docs/phase6_summary.md) instead of mutual_info_classif."""
    valid = features.notna().all(axis=1) & label.notna()
    X, y = features.loc[valid], label.loc[valid]
    if len(X) == 0:
        raise ValueError("No valid (non-NaN) rows to compute redundancy on")

    if len(X) > max_rows:
        sample_idx = X.sample(n=max_rows, random_state=random_state).index
        X_mi, y_mi = X.loc[sample_idx], y.loc[sample_idx]
    else:
        X_mi, y_mi = X, y

    mi_func = mutual_info_regression if regression else mutual_info_classif
    mi = mi_func(X_mi, y_mi, random_state=random_state)
    mi_series = pd.Series(mi, index=X.columns).sort_values(ascending=False)

    corr = X.corr().abs()
    kept, dropped = [], {}
    for feat in mi_series.index:  # process highest-MI first so it "wins" any redundancy tie
        redundant_to = next((k for k in kept if corr.loc[feat, k] > corr_threshold), None)
        if redundant_to is None:
            kept.append(feat)
        else:
            dropped[feat] = redundant_to

    return kept, {"mutual_info": mi_series.to_dict(), "kept": kept, "dropped": dropped, "n_rows": len(X)}


def write_report(report: dict, path: str) -> None:
    lines = [
        "# Feature redundancy report",
        "",
        "Auto-generated by `quant_bot.features.pipeline.prune_redundant` "
        "(SPEC.md section 5). Regenerate whenever the candidate feature list "
        f"in `quant_bot/features/build.py` changes. Computed on {report['n_rows']:,} rows.",
        "",
        "## Mutual information with label (all candidates, highest first)",
        "",
    ]
    for feat, mi in sorted(report["mutual_info"].items(), key=lambda kv: -kv[1]):
        if feat in report["kept"]:
            marker = "**KEPT**"
        else:
            marker = f"dropped — redundant with `{report['dropped'][feat]}`"
        lines.append(f"- `{feat}`: MI={mi:.5f} — {marker}")

    lines += ["", f"## Kept ({len(report['kept'])} of {len(report['mutual_info'])})", ""]
    lines += [f"- `{f}`" for f in report["kept"]]

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
